"""Downloads Material Icons (Apache-2.0, @material-design-icons/svg) and writes Swift path data.

usage: python Tools/fetch_icons.py
Output: PodTube/Sources/App/IconData.swift  (generated, committed so CI needs no network for this)
iOS 12 has no SF Symbols, so icons are drawn from SVG path data at runtime (see Icons.swift).
"""
import os
import re
import sys
import urllib.request

VERSION = "0.14.13"
BASE = "https://cdn.jsdelivr.net/npm/@material-design-icons/svg@%s/%s/%s.svg"

FILLED = """home subscriptions account_circle search airplay notifications more_vert arrow_back close thumb_up
thumb_down share file_download playlist_add watch_later history playlist_play settings play_arrow pause skip_next
skip_previous replay_10 forward_10 fullscreen fullscreen_exit closed_caption expand_more expand_less
keyboard_arrow_down check tune sort flag delete north_west speed hd language timer repeat info brightness_4
translate add playlist_add_check queue_music video_library thumb_up_off_alt thumb_down_off_alt closed_caption_off
bookmark bookmark_border visibility send content_copy link open_in_new mic refresh cloud_download offline_pin
download_done shuffle play_circle verified notifications_none whatshot explore wifi volume_up sync clear_all
edit more_horiz chevron_right chevron_left arrow_drop_down schedule picture_in_picture_alt skip_next
radio_button_checked radio_button_unchecked check_circle person logout login lock storage cloud_off
slow_motion_video music_note live_tv sensors dark_mode light_mode contrast aspect_ratio arrow_forward
swap_vert screen_rotation volume_off format_list_bulleted play_arrow audiotrack analytics
""".split()

OUTLINED = """home subscriptions account_circle notifications thumb_up thumb_down share watch_later settings history
bookmark_border playlist_add file_download flag video_library closed_caption info delete music_note
""".split()


def fetch(style, name):
    url = BASE % (VERSION, style, name)
    try:
        with urllib.request.urlopen(url, timeout=20) as r:
            return r.read().decode("utf8")
    except Exception as e:
        return None


def paths_of(svg):
    out = []
    for m in re.finditer(r"<path\b([^>]*)/?>", svg):
        attrs = m.group(1)
        if 'fill="none"' in attrs:
            continue
        d = re.search(r'\bd="([^"]+)"', attrs)
        if d:
            out.append(d.group(1))
    return " ".join(out)


entries = {}
missing = []
for style, names in (("filled", FILLED), ("outlined", OUTLINED)):
    for n in dict.fromkeys(names):
        svg = fetch(style, n)
        if not svg:
            missing.append("%s/%s" % (style, n))
            continue
        d = paths_of(svg)
        if not d:
            missing.append("%s/%s (no path)" % (style, n))
            continue
        key = n if style == "filled" else n + "_outline"
        entries[key] = d

out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PodTube", "Sources", "App", "IconData.swift")
with open(out_path, "w", encoding="utf8", newline="\n") as f:
    f.write("// Generated by Tools/fetch_icons.py from Material Icons (Apache License 2.0). Do not edit by hand.\n")
    f.write("// 24x24 viewBox SVG path data.\n")
    f.write("enum IconData {\n    static let paths: [String: String] = [\n")
    for k in sorted(entries):
        f.write('        "%s": "%s",\n' % (k, entries[k]))
    f.write("    ]\n}\n")
print("wrote %d icons" % len(entries))
if missing:
    print("missing:", ", ".join(missing))
